    public const string RecentsId = "recents";
    public const string SearchId = "search";
    public const int RecentLimit = 24;

    public static IReadOnlyList<EmojiCategory> Categories { get; } = BuildCategories();

    public static IReadOnlyList<EmojiItem> All { get; } =
        Categories.SelectMany(c => c.Items).DistinctBy(e => e.Glyph).ToArray();

    public static IReadOnlyList<EmojiItem> Search(string query)
    {
        string folded = new(TextFolding.ToLetters(query));
        if (folded.Length == 0)
        {
            return [];
        }

        return All.Where(item => KeywordFold(item.Keywords).Contains(folded, StringComparison.Ordinal)).ToArray();
    }

    /// <summary>Moves <paramref name="glyph"/> to the front of the recent list (max <see cref="RecentLimit"/>).</summary>
    public static List<string> PushRecent(IEnumerable<string>? current, string glyph, int max = RecentLimit)
    {
        var result = new List<string>(max);
        if (!string.IsNullOrWhiteSpace(glyph))
        {
            result.Add(glyph);
        }

        if (current is not null)
        {
            foreach (string item in current)
            {
                if (string.IsNullOrWhiteSpace(item) || item == glyph)
                {
                    continue;
                }

                result.Add(item);
                if (result.Count >= max)
                {
                    break;
                }
            }
        }

        return result;
    }

    public static IReadOnlyList<EmojiItem> ResolveRecent(IEnumerable<string>? glyphs)
    {
        if (glyphs is null)
        {
            return [];
        }

        var map = All.ToDictionary(e => e.Glyph, StringComparer.Ordinal);
        var list = new List<EmojiItem>();
        foreach (string glyph in glyphs)
        {
            if (map.TryGetValue(glyph, out EmojiItem? item))
            {
                list.Add(item);
            }
            else if (!string.IsNullOrWhiteSpace(glyph))
            {
                list.Add(new EmojiItem(glyph, string.Empty));
            }
        }

        return list;
    }

    private static string KeywordFold(string keywords) => new(TextFolding.ToLetters(keywords));

