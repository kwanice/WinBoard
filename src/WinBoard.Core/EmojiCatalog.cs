namespace WinBoard.Core;

/// <summary>One emoji with bilingual (FR/EN) search keywords.</summary>
public sealed record EmojiItem(string Glyph, string Keywords);

/// <summary>Gboard-style emoji group. <see cref="Items"/> is empty for virtual tabs (récents, recherche).</summary>
public sealed record EmojiCategory(string Id, string Label, string Icon, IReadOnlyList<EmojiItem> Items);

/// <summary>
/// Offline emoji catalog for the WinBoard panel. No network, no glyph download.
